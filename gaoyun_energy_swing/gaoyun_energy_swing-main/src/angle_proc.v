//=============================================================================
// 模块:angle_proc  摆杆角度处理
// 功能:
//   1) 把 ADC 原始值(0~4092)转换成以“倒立平衡点”为零点的有符号摆角 phi
//   2) 用“连续增量积分 + 一阶低通”求摆角速度 omega(避免过零点卷绕跳变)
//   3) 查表得到 cos(phi),供能量法起摆使用
// 说明:
//   phi  : 0 表示摆杆倒立,±2048 约等于 ±180°,单位是 ADC 的 LSB
//   omega: 单位是 LSB / 每个采样周期(3ms)
//   cos_phi: Q14 定点,1.0 -> 16384
//=============================================================================
module angle_proc #(

    parameter [11:0] ZERO_RAW = 12'd3150    // 倒立(平衡)位置对应的 ADC 原始值

)(

    input                       clk_50m ,
    input                       rst_n   ,
    input       [11:0]          theta_raw,  // ADC 原始角度
    input                       tick    ,   // 角度采样有效脉冲(每 3ms 一次)

    output reg signed [15:0]    phi     ,   // 摆角(0=倒立)
    output reg signed [15:0]    omega   ,   // 摆角速度
    output reg signed [15:0]    cos_phi     // cos(phi) Q14

);

    //------------------------------------------------------------------
    // 1) 原始值 -> 以倒立点为零点的有符号摆角
    //    减去倒立点后按 4096 取模,再映射到 -2048 ~ +2047
    //------------------------------------------------------------------
    wire [11:0]         diff_u  = theta_raw - ZERO_RAW;
    wire signed [12:0]  phi_new = (diff_u > 12'd2047)
                                ? ($signed({1'b0, diff_u}) - 13'sd4096)
                                :  $signed({1'b0, diff_u});

    //------------------------------------------------------------------
    // 2) 角速度:先做增量解卷绕,再一阶低通
    //    d_raw 是两次采样的原始差,卷绕到 ±2048 后就是真实增量
    //    摆杆在 3ms 内不可能转过 180°,所以这种解卷绕是安全的
    //------------------------------------------------------------------
    reg  [11:0]         theta_last;
    wire [11:0]         d_raw = theta_raw - theta_last;
    wire signed [12:0]  d_s_raw = (d_raw > 12'd2047)
                              ? ($signed({1'b0, d_raw}) - 13'sd4096)
                              :  $signed({1'b0, d_raw});

    //------------------------------------------------------------------
    // 2b) 单拍增量限幅(抗采样毛刺)  [2026/9/17 新增]
    //     摆杆在 3ms 内物理上转不过 D_MAX 个 LSB:等效摆长约 9.5cm,
    //     最大角速度 2*w0 = 2*sqrt(g/l) ≈ 20rad/s,折合 2.0 LSB/3ms 的
    //     角度增量约 39 LSB。取 D_MAX=64(约 1.6 倍余量)。
    //     实测未限幅时约 1.5% 的帧出现 400+ LSB 的单帧跳变(ADC 并行总线
    //     在快速翻转瞬间被采到)。这种毛刺经微分放大后直接顶死电机指令,
    //     是平衡环一进 BALANCE 就饱和的根因,故此处限幅并整拍丢弃。
    //------------------------------------------------------------------
    // ★ [2026/10/17 修正] 256 -> 64。之前把它提到 256 的依据是'实测 |dphi| 峰值 148',
//    但那个 148 本身是 ADC 毛刺: 摆杆物理极限约 24 rad/s = 47 LSB/3ms,
//    超过 ~50 的都不可能是真实运动; 而且毛刺会在一帧内符号翻转。
//    提到 256 之后 ±120~180 的毛刺不再被过滤, 直接进控制环给 D 项一个大踢,
//    这很可能是'稳 2~8 秒就掉'的主因之一。64 (=32 rad/s) 已比物理极限高 36%,够用。
localparam signed [12:0] D_MAX = 13'sd64;
    wire signed [12:0]  d_s    = (d_s_raw > D_MAX)  ? D_MAX
                              : (d_s_raw < -D_MAX) ? -D_MAX
                              : d_s_raw;
    wire                glitch = (d_s_raw != d_s);

    // 低通系数 1/2:omega = 1/2*omega + 1/2*增量  [2026/9/17 由 1/4 改 1/2]
    //   直流增益都是 1(0.75+0.25 = 0.5+0.5),但等效时间常数从
    //     T/ln(1/0.75) = 3/0.2877 = 10.4ms  降到  T/ln(2) = 3/0.693 = 4.3ms
    //   实测极限环频率约 2.8Hz,在这个频率上滞后角从 16.8° 降到 6.9°,
    //   换回约 10° 相位裕度。极限环(颤振)幅度正比于回路总延迟,这是回路里
    //   唯一能软件侧削减的一块(采样 3ms 和电机 20~50ms 都动不了)。
    //   代价:D 项对 ADC 噪声更敏感,所以下面的 D_MAX 限幅要保住。
    // 复位后的第一次采样不做微分(theta_last 尚未初始化,增量无意义),
    // 否则上电瞬间会出现一个大角速度毛刺,让起摆控制器误动作。
    // 注意:上电时若没有按复位键,rst_n 一直为高,上面的复位分支不会执行,
    //      因此这里给出上电初值 1,保证“上电后第一次采样”同样被屏蔽。
    reg                 first = 1'b1;
    wire signed [15:0]  omega_next = first ? 16'sd0
                                          : (omega - (omega >>> 1) + (d_s >>> 1));

    //------------------------------------------------------------------
    // 3) 余弦查表:idx = |phi| >> 3,0~255 对应 0~180°
    //------------------------------------------------------------------
    wire signed [12:0]  phi_abs = phi_new[12] ? (13'sd0 - phi_new) : phi_new;
    wire [8:0]          idx_tmp = phi_abs[11:3];
    wire [7:0]          cos_idx = (idx_tmp > 9'd255) ? 8'd255 : idx_tmp[7:0];

    wire signed [15:0]  cos_val;

    cos_lut cos_lut_inst(
        .idx     (cos_idx),
        .cos_val (cos_val)
    );

    //------------------------------------------------------------------
    // 采样节拍更新
    //------------------------------------------------------------------
    always@(posedge clk_50m or negedge rst_n) begin
        if(!rst_n) begin
            theta_last <= 12'd0;
            phi        <= 16'sd0;
            omega      <= 16'sd0;
            cos_phi    <= 16'sd16384;
            first      <= 1'b1;
        end else if(tick) begin
            // theta_last 始终更新,保证下一拍的增量窗口严格还是 3ms
            theta_last <= theta_raw;
            // 毛刺拍:phi/omega/cos_phi 全部保持上一拍值,不把垃圾喂给控制器
            if(!glitch) begin
                phi     <= phi_new;
                omega   <= omega_next;
                cos_phi <= cos_val;
            end
            first <= 1'b0;
        end
    end

endmodule
